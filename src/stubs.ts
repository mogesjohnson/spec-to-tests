// Finds function, interface, class and type names a spec mentions, and renders throwing stubs.

export interface StubSymbol {
  name: string;
  kind: 'function' | 'interface' | 'class' | 'type';
}

const IDENT = '[A-Za-z_$][\\w$]*';
const INLINE = /`([^`\n]+)`/g;
const FN_CALL = new RegExp(`^(?:${IDENT}\\.)*(${IDENT})\\s*\\([^)]*\\)$`);
const DECL = new RegExp(`^(?:export\\s+)?(?:declare\\s+)?(?:async\\s+)?(function|interface|class|type)\\s+(${IDENT})`);
const API_HEADING = /^#{1,6}\s+(interface|api)\b/i;

export function findSymbols(markdown: string): StubSymbol[] {
  const out = new Map<string, StubSymbol>();
  const add = (name: string, kind: StubSymbol['kind']) => {
    if (!out.has(name)) out.set(name, { name, kind });
  };
  const lines = markdown.split(/\r?\n/);
  let inApi = false;
  let fence: string | null = null;
  for (const line of lines) {
    const fm = /^\s*(```|~~~)\s*(\w*)/.exec(line);
    if (fm) {
      fence = fence === null ? fm[2].toLowerCase() : null;
      continue;
    }
    if (fence !== null) {
      if (inApi && (fence === 'ts' || fence === 'typescript')) {
        const m = DECL.exec(line.trim());
        if (m) add(m[2], m[1] as StubSymbol['kind']);
      }
      continue;
    }
    if (/^#{1,6}\s/.test(line)) inApi = API_HEADING.test(line);
    for (const m of line.matchAll(INLINE)) {
      const code = m[1].trim();
      const d = DECL.exec(code);
      if (d) add(d[2], d[1] as StubSymbol['kind']);
      else {
        const f = FN_CALL.exec(code);
        if (f) add(f[1], 'function');
      }
    }
  }
  return [...out.values()];
}

export function renderStubs(symbols: StubSymbol[], specPath: string): string {
  const body = symbols.map((s) => {
    switch (s.kind) {
      case 'function':
        return `export function ${s.name}(..._args: unknown[]): never {\n  throw new Error('not implemented: ${s.name}');\n}`;
      case 'class':
        return `export class ${s.name} {\n  constructor(..._args: unknown[]) {\n    throw new Error('not implemented: ${s.name}');\n  }\n}`;
      case 'interface':
        return `// eslint-disable-next-line @typescript-eslint/no-empty-interface, @typescript-eslint/no-empty-object-type\nexport interface ${s.name} {}`;
      case 'type':
        return `export type ${s.name} = unknown;`;
    }
  });
  return `// Generated by spec-to-tests from ${specPath}. Replace each stub with the real code.\n\n${body.join('\n\n')}\n`;
}
