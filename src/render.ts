// Renders the acceptance test file and the criteria checklist.
import type { Criterion } from './extract.js';
import type { StubSymbol } from './stubs.js';
import { vagueWords } from './vague.js';

export const testName = (c: Criterion) => `${c.id} ${c.text}`;
const quote = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

export interface RenderInput {
  title: string;
  specPath: string;
  criteria: Criterion[];
  symbols: StubSymbol[];
  /** Import path from the test file to the stubs module, without extension. */
  stubsImport?: string;
}

export function renderTestFile(input: RenderInput): string {
  const out = [`// Generated by spec-to-tests from ${input.specPath}. Turn each todo into a real test.`];
  out.push(`import { describe, it } from 'vitest';`);
  const values = input.symbols.filter((s) => s.kind === 'function' || s.kind === 'class').map((s) => s.name);
  const types = input.symbols.filter((s) => s.kind === 'interface' || s.kind === 'type').map((s) => s.name);
  if (input.stubsImport && values.length) {
    out.push('// eslint-disable-next-line @typescript-eslint/no-unused-vars');
    out.push(`import { ${values.join(', ')} } from '${input.stubsImport}.js';`);
  }
  if (input.stubsImport && types.length) {
    out.push('// eslint-disable-next-line @typescript-eslint/no-unused-vars');
    out.push(`import type { ${types.join(', ')} } from '${input.stubsImport}.js';`);
  }
  out.push('', `describe(${quote(input.title)}, () => {`);
  for (const c of input.criteria) {
    if (c.vague) out.push(`  // ${c.id} needs clarification (${vagueWords(c.text).join(', ')}): ${c.text.replace(/\n/g, ' ')}`);
    else out.push(`  it.todo(${quote(testName(c))});`);
  }
  if (!input.criteria.length) out.push('  it.todo(\'no acceptance criteria found in the spec\');');
  out.push('});', '');
  return out.join('\n');
}

export function renderChecklist(input: RenderInput & { testFile: string }): string {
  const link = (c: Criterion) => `[${c.id}](${input.testFile}#${c.id.toLowerCase()})`;
  const testable = input.criteria.filter((c) => !c.vague);
  const vague = input.criteria.filter((c) => c.vague);
  const out = [`# ${input.title}: acceptance checklist`, '', `Source: \`${input.specPath}\`. Tests: [\`${input.testFile}\`](${input.testFile}).`, ''];
  out.push('## Criteria', '');
  if (!testable.length) out.push('None found.');
  for (const c of testable) out.push(`- [ ] ${link(c)} ${c.text} (test: \`${testName(c)}\`, spec line ${c.line})`);
  out.push('', '## Needs clarification', '');
  if (!vague.length) out.push('None.');
  else out.push('These have no number or unit, so no test was written. Add a measurable bound to the spec.', '');
  for (const c of vague) out.push(`- [ ] ${c.id} ${c.text} (vague: ${vagueWords(c.text).join(', ')}; spec line ${c.line})`);
  if (input.symbols.length) {
    out.push('', '## Interface stubs', '');
    for (const s of input.symbols) out.push(`- \`${s.name}\` (${s.kind})`);
  }
  out.push('');
  return out.join('\n');
}
